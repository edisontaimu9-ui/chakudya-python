#!/usr/bin/env python3
"""Regenerates chakudya/routes.py from tool/methods.json (copied from the JS SDK's scripts/methods.json).
Usage: python3 tool/generate.py"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
m = json.load(open(ROOT / "tool" / "methods.json"))["generated"]
lines = ['"""GENERATED by tool/generate.py from tool/methods.json. Do not edit by hand."""', "",
         "GENERATED_ROUTES = {"]
for ns in sorted(m):
    lines.append(f'    "{ns}": {{')
    for name in sorted(m[ns]):
        lines.append(f'        "{name}": "{m[ns][name]}",')
    lines.append("    },")
lines.append("}")
(ROOT / "chakudya" / "routes.py").write_text("\n".join(lines) + "\n")
print(len(m), "namespaces,", sum(len(v) for v in m.values()), "routes")
